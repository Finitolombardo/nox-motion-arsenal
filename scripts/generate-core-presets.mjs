// Regenerates src/motion-arsenal/data/generatedCorePresets.ts from the niche
// preset records that live inside the canonical core components. Those records
// are the runtime source of truth; the arsenal must not keep a hand-copied
// second version of them that can silently drift.
//
//   node scripts/generate-core-presets.mjs          # write
//   node scripts/generate-core-presets.mjs --check  # fail if stale (used by tests)
import fs from 'node:fs';
import path from 'node:path';
import { loadCatalogMeta, repoRoot } from './lib/loadCatalogMeta.mjs';
import { loadCorePresetSources } from './lib/loadCorePresetSources.mjs';

const OUT = path.join(repoRoot, 'src', 'motion-arsenal', 'data', 'generatedCorePresets.ts');

const NICHE_LABELS = {
  restaurant: 'Restaurant / Hospitality',
  beauty: 'Beauty / Wellness',
  fitness: 'Fitness / Sport',
  'local-service': 'Local Service / Handwerk',
  'real-estate': 'Real Estate',
  automotive: 'Automotive',
  healthcare: 'Healthcare / Praxis',
  finance: 'Finance / Kanzlei',
  saas: 'SaaS / Tech',
  ecommerce: 'E-Commerce',
  luxury: 'Luxury / Premium',
  creator: 'Creator / Personal Brand',
};

// Heuristic-free profile read: a preset either names its own profile or is
// classified by the load-bearing values it actually sets.
function performanceProfile(values) {
  if (typeof values.performanceProfile === 'string') return values.performanceProfile;
  const density = Number(values.density ?? values.atmosphereDensity ?? NaN);
  if (Number.isFinite(density)) return density >= 3000 || density >= 20 ? 'cinematic' : density <= 2000 || density <= 12 ? 'lite' : 'balanced';
  return 'balanced';
}

function mobileProfile(values) {
  const profile = performanceProfile(values);
  return profile === 'cinematic' ? 'balanced' : profile === 'lite' ? 'compact' : 'balanced';
}

export async function buildGeneratedPresets() {
  const { byId } = await loadCatalogMeta();
  const sources = await loadCorePresetSources();
  const out = {};
  for (const [coreId, record] of sources) {
    const meta = byId.get(coreId);
    if (!meta) throw new Error(`core ${coreId} is not in the catalog`);
    const controlKeys = new Set(meta.props.map((p) => p.key));
    out[coreId] = Object.entries(record).map(([niche, values]) => {
      // Only keys the arsenal can actually drive survive; everything else is
      // internal component state the UI has no control for.
      const props = {};
      for (const [key, value] of Object.entries(values)) {
        if (key === 'label') continue;
        if (!controlKeys.has(key)) continue;
        if (value === undefined || value === null) continue;
        props[key] = value;
      }
      if (controlKeys.has('preset')) props.preset = niche;
      return {
        id: `${coreId}::${niche}`,
        label: values.label ?? NICHE_LABELS[niche] ?? niche,
        niche,
        props,
        performanceProfile: performanceProfile(values),
        mobileProfile: mobileProfile(values),
        source: 'component',
      };
    });
  }
  return out;
}

function render(data) {
  return `// GENERATED by scripts/generate-core-presets.mjs — do not edit by hand.
// Mirrors the niche preset records inside the canonical core components so the
// preset picker loads the complete curated state instead of relying on the
// component's internal \`?? preset.x\` fallbacks (the arsenal always passes
// every prop explicitly, which would otherwise defeat them).
import type { NicheId } from '../types';

export interface GeneratedCorePreset {
  id: string;
  label: string;
  niche: NicheId;
  props: Record<string, number | string | boolean>;
  performanceProfile: 'lite' | 'balanced' | 'cinematic';
  mobileProfile: 'compact' | 'balanced' | 'full';
  source: 'component';
}

export const GENERATED_CORE_PRESETS: Record<string, GeneratedCorePreset[]> = ${JSON.stringify(data, null, 2)};
`;
}

const data = await buildGeneratedPresets();
const next = render(data);
if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== next) {
    console.error('[core-presets] STALE — run `node scripts/generate-core-presets.mjs`');
    process.exit(1);
  }
  console.log(`[core-presets] PASS generated presets match component sources (${Object.keys(data).length} cores)`);
} else {
  fs.writeFileSync(OUT, next);
  console.log(`[core-presets] wrote ${OUT} (${Object.values(data).flat().length} presets across ${Object.keys(data).length} cores)`);
}
